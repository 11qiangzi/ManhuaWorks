interface Project {

















  id: string

















  title?: string

















  name?: string

















  description?: string | null

















  status?: number

















  cover_url?: string | null

















  created_at?: string

















  updated_at?: string

















}



































const projects = ref<Project[]>([])

















const loading = ref(true)

















const error = ref<string | null>(null)
















const isAuthError = ref(false)
















const showLogin = ref(false)

















const statusFilter = ref<'all' | number>('all')



































const STATUS_META: Record<number, { label: string; icon: string; color: string }> = {

















  0: { label: '草稿', icon: '📝', color: '#f59e0b' },

















  1: { label: '进行中', icon: '🔵', color: '#6366f1' },

















  2: { label: '审核中', icon: '🟢', color: '#10b981' },

















  3: { label: '已完成', icon: '✅', color: '#94a3b8' },

















}



































function getAuthHeaders(): Record<string, string> {

















  try {

















    const token = localStorage.getItem('token') || localStorage.getItem('mhw.access_token')

















    return token ? { Authorization: `Bearer ${token}` } : {}

















  } catch {

















    return {}

















  }

















}



































async function loadProjects(): Promise<void> {

















  loading.value = true

















  error.value = null
















isAuthError.value = false

















  try {

















    const r = await fetch('/api/v1/projects', { headers: getAuthHeaders() })

















    if (r.status === 401) { error.value = '请先登录后再查看项目'; isAuthError.value = true; return }
















    if (!r.ok) throw new Error(`HTTP ${r.status}`)

















    const raw = await r.json()

















    projects.value = raw?.data?.items ?? raw?.data?.list ?? []

















  } catch (e) {

















    error.value = (e as Error).message

















    projects.value = []

















  } finally {

















    loading.value = false

















  }

















}



































onMounted(loadProjects)



































const filteredProjects = computed(() => {

















  if (statusFilter.value === 'all') return projects.value

















  return projects.value.filter((p) => p.status === statusFilter.value)

















})



































function openProject(p: Project): void {

















  router.push(`/projects/${p.id}`)

















}



































function openInStudio(): void {

















  router.push('/create/animation')

















}



































function fmt(t?: string): string {

















  if (!t) return 'Unknown';
















  const d = new Date(t)
















  const diff = Date.now() - d.getTime()

















  if (diff < 3_600_000) return `${Math.floor(diff / 60_000)} 分钟前`

















  if (diff < 86_400_000) return `${Math.floor(diff / 3_600_000)} 小时前`

















  if (diff < 7 * 86_400_000) return `${Math.floor(diff / 86_400_000)} 天前`

















  return d.toLocaleDateString('zh-CN')

















}

















